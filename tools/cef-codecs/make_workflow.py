#!/usr/bin/env python3
"""Writes .github/workflows/cef-codecs.yml: a chain of identical build stages, which YAML can't loop."""
import os

STAGES = 10

HEAD = """name: cef-codecs
# Builds CEF with the H.264/AAC (MP4) video codecs, which the stock CEF downloads leave out, on free
# GitHub runners. A Chromium build takes far longer than one job may run (6 hours), so the build is a
# chain of jobs: each restores the previous job's work folder, builds until its deadline, and saves the
# folder for the next. See tools/cef-codecs/stage.py. The result is uploaded to the draft release
# `cef-codecs-<version>`, where release.yml picks it up instead of the stock CEF.
#
# Generated by tools/cef-codecs/make_workflow.py: edit that and run it again.
on:
  push:
    branches: [ci/cef-codecs]
    paths: [".github/workflows/cef-codecs.yml", "tools/cef-codecs/**"]
  workflow_dispatch:
    inputs:
      os:
        description: Which CEF to build
        type: choice
        options: [windows, linux]
        default: windows
      resume_run:
        description: To carry on a chain that stopped, the id of its run (its saved work folder is kept 3 days)
        type: string
        default: ""
      resume_state:
        description: With resume_run, the number of the last stage that saved its work folder there
        type: string
        default: ""
permissions:
  contents: write
  actions: read
concurrency:
  group: cef-codecs-${{ inputs.os || 'windows' }}
jobs:
"""


def stage(n):
    prev = f"stage{n - 1}"
    s = f"  stage{n}:\n"
    if n > 1:
        s += f"    needs: {prev}\n    if: needs.{prev}.outputs.done == 'false'\n"
    s += f"""    runs-on: ${{{{ (inputs.os || 'windows') == 'windows' && 'windows-2025' || 'ubuntu-24.04' }}}}
    timeout-minutes: 358
    outputs:
      done: ${{{{ steps.build.outputs.done }}}}
    defaults:
      run:
        shell: bash
    steps:
      - name: Deadline
        # Build for at most 4 hours 45 minutes of this job, leaving time to save the work folder.
        run: echo "DEADLINE=$(( $(date +%s) + 285 * 60 ))" >> "$GITHUB_ENV"
      - uses: actions/checkout@v4
        with: {{ path: repo }}
      - name: Make room and set up
        run: bash repo/tools/cef-codecs/setup.sh
"""
    if n > 1:
        s += f"""      - uses: actions/download-artifact@v4
        with:
          name: cef-codecs-${{{{ inputs.os || 'windows' }}}}-state-{n - 1}
          path: ${{{{ env.STATE_DIR }}}}
      - name: Restore the work folder
        run: bash repo/tools/cef-codecs/state.sh restore
"""
    else:
        s += """      - uses: actions/download-artifact@v4
        if: inputs.resume_run != ''
        with:
          name: cef-codecs-${{ inputs.os || 'windows' }}-state-${{ inputs.resume_state }}
          path: ${{ env.STATE_DIR }}
          run-id: ${{ inputs.resume_run }}
          github-token: ${{ github.token }}
      - name: Restore the work folder of the stopped run
        if: inputs.resume_run != ''
        run: bash repo/tools/cef-codecs/state.sh restore
      - name: Fetch Chromium and CEF
        if: inputs.resume_run == ''
        run: |
          "$PYTHON" repo/tools/cef-codecs/stage.py "$WORK" "$DEADLINE" --checkout
"""
    s += f"""      - name: Windows SDK
        if: runner.os == 'Windows'
        shell: pwsh
        run: repo/tools/cef-codecs/win-sdk.ps1 -Work $env:WORK
      - name: Linux build dependencies
        if: runner.os == 'Linux'
        # The Linux CEF builds against Chromium's Debian sysroot (use_sysroot=true in stage.py), as the
        # official CEF builds do: it has every header and library the build needs, and the result runs
        # on older distributions too. install-build-deps still provides the host tools.
        run: |
          sudo "$WORK/chromium/src/build/install-build-deps.sh" --no-prompt --no-chromeos-fonts || sudo "$WORK/chromium/src/build/install-build-deps.sh" --no-prompt
          "$PYTHON" "$WORK/chromium/src/build/linux/sysroot_scripts/install-sysroot.py" --arch=amd64
      - name: Build until the deadline
        id: build
        run: |
          set +e
          "$PYTHON" repo/tools/cef-codecs/stage.py "$WORK" "$DEADLINE"
          code=$?
          set -e
          df -h "$WORK" || true
          if [ $code -eq 0 ]; then echo "done=true" >> "$GITHUB_OUTPUT"
          elif [ $code -eq 75 ]; then echo "done=false" >> "$GITHUB_OUTPUT"
          else exit $code; fi
      - name: Save the work folder for the next stage
        if: steps.build.outputs.done == 'false'
        run: bash repo/tools/cef-codecs/state.sh save
      - uses: actions/upload-artifact@v4
        if: steps.build.outputs.done == 'false'
        with:
          name: cef-codecs-${{{{ inputs.os || 'windows' }}}}-state-{n}
          path: ${{{{ env.STATE_DIR }}}}/state.tar.zst
          retention-days: 3
          compression-level: 0
      - name: Publish the finished CEF
        if: steps.build.outputs.done == 'true'
        env:
          GH_TOKEN: ${{{{ github.token }}}}
        run: bash repo/tools/cef-codecs/publish.sh
"""
    return s


TAIL = f"""  out-of-stages:
    needs: stage{STAGES}
    if: needs.stage{STAGES}.outputs.done == 'false'
    runs-on: ubuntu-24.04
    steps:
      - run: echo "{STAGES} stages weren't enough to finish the build." && exit 1
"""

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "..", ".github", "workflows", "cef-codecs.yml")
with open(out, "w") as f:
    f.write(HEAD + "".join(stage(n) for n in range(1, STAGES + 1)) + TAIL)
